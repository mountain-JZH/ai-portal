import assert from 'node:assert/strict'
import path from 'node:path'

export async function checkPhase3({ page, context, base, output, checks, sample }) {
  // Textarea values use LF regardless of a Windows fixture's line endings.
  sample = sample.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base + '/admin/news/new')
  await page.getByLabel('新闻类型', { exact: true }).selectOption('新能源行业早报')
  assert.equal(await page.getByRole('checkbox').isChecked(), false)
  await page.getByPlaceholder('请输入新闻标题').fill('新能源行业早报｜2026-11-16')
  await page.getByPlaceholder('请输入新闻摘要').fill('虚构排版及流程测试，不用于正式发布。')
  await page.getByPlaceholder('请输入新闻正文').fill(sample)
  const writes = []
  page.on('request', request => { if (['POST', 'PUT', 'PATCH'].includes(request.method())) writes.push(request.url()) })
  await page.getByRole('button', { name: '展开预览', exact: true }).click()
  const preview = page.getByRole('region', { name: '新闻预览' })
  for (const name of ['今日速览', '今日重点', '江苏及周边动态', '行业快讯', '持续关注']) await preview.getByRole('heading', { name, exact: true }).waitFor()
  assert.equal(writes.length, 0)
  await page.getByPlaceholder('请输入新闻正文').fill(sample + '\n\n实时预览更新')
  await preview.getByText('实时预览更新', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(output, 'preview-desktop.png'), fullPage: true })
  for (const width of [375, 320]) {
    await page.setViewportSize({ width, height: 812 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'preview horizontal overflow at ' + width)
  }
  await page.screenshot({ path: path.join(output, 'preview-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await page.getByText('草稿保存成功', { exact: true }).waitFor()
  const all = await (await context.request.get(base + '/api/admin/news')).json()
  const created = all.find(n => n.id > 3)
  assert.equal(created.is_published, 0)
  assert.equal(created.content, sample + '\n\n实时预览更新')
  assert.equal((await context.request.get(base + '/api/news/' + created.id)).status(), 404)
  assert.ok(!(await (await context.request.get(base + '/api/news')).json()).some(n => n.id === created.id))
  await page.goto(base + '/admin/news/' + created.id + '/edit')
  await page.getByRole('button', { name: '展开预览', exact: true }).click()
  await preview.getByRole('heading', { name: '今日速览', exact: true }).waitFor()
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await page.getByText('草稿保存成功', { exact: true }).waitFor()
  assert.equal((await (await context.request.get(base + '/api/admin/news/' + created.id)).json()).is_published, 0)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base + '/admin/news')
  const row = () => page.getByRole('row').filter({ has: page.locator('a[href="/admin/news/' + created.id + '/edit"]') })
  await row().getByRole('button', { name: '发布', exact: true }).click()
  await page.getByText('新闻已发布', { exact: true }).waitFor()
  assert.equal((await context.request.get(base + '/api/news/' + created.id)).status(), 200)
  await page.goto(base + '/news/' + created.id)
  await page.getByRole('heading', { name: '今日速览', exact: true }).waitFor()
  const official = await page.locator('.news-markdown').innerHTML()
  await page.goto(base + '/admin/news/' + created.id + '/edit')
  await page.getByPlaceholder('请输入新闻标题').waitFor()
  assert.equal(await page.getByRole('checkbox').isChecked(), true)
  await page.getByRole('button', { name: '展开预览', exact: true }).click()
  assert.equal(await page.locator('.news-markdown').innerHTML(), official)
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await page.getByText('新闻修改成功', { exact: true }).waitFor()
  assert.equal((await (await context.request.get(base + '/api/admin/news/' + created.id)).json()).is_published, 1)
  await page.goto(base + '/news')
  await page.getByLabel('新闻筛选', { exact: true }).selectOption('brief')
  await page.waitForFunction(() => document.querySelectorAll('.news-card').length === 2)
  await page.getByLabel('新闻筛选', { exact: true }).selectOption('other')
  assert.equal(await page.locator('.news-card').count(), 1)
  await page.getByLabel('新闻筛选', { exact: true }).selectOption('all')
  assert.equal(await page.locator('.news-card').count(), 3)
  await page.goto(base + '/admin/news')
  // A failed publish request must not optimistically change the row status.
  await page.route('**/api/news/*/publish', route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"detail":"test failure"}' }))
  await row().getByRole('button', { name: '下架', exact: true }).click()
  await page.getByText('操作失败，请稍后重试', { exact: true }).waitFor()
  assert.equal((await context.request.get(base + '/api/news/' + created.id)).status(), 200)
  await page.unroute('**/api/news/*/publish')
  await row().getByRole('button', { name: '下架', exact: true }).click()
  await page.getByText('新闻已下架', { exact: true }).waitFor()
  assert.equal((await context.request.get(base + '/api/news/' + created.id)).status(), 404)
  page.once('dialog', dialog => dialog.accept())
  await row().getByRole('button', { name: '删除', exact: true }).click()
  await page.getByText('新闻删除成功', { exact: true }).waitFor()
  assert.equal((await context.request.get(base + '/api/admin/news/' + created.id)).status(), 404)
  checks.push('live preview without writes, draft save/edit, publish, identical preview/detail, history filters, failure feedback, withdraw/delete')
  await page.goto(base + '/admin/news/new')
  await page.getByPlaceholder('请输入新闻标题').waitFor()
  assert.equal(await page.getByRole('checkbox').isChecked(), true)
  await page.getByPlaceholder('请输入新闻标题').fill('普通新闻创建回归')
  await page.getByRole('button', { name: '发布新闻', exact: true }).click()
  await page.getByText('新闻发布成功', { exact: true }).waitFor()
  checks.push('ordinary news retains default publish behavior')
}
